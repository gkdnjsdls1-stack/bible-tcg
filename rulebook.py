"""룰북을 뽑는다. python3 rulebook.py -> rules.md

수치는 한 줄도 손으로 적지 않는다 — 전부 cards.json에서 읽는다 (약점/저항·카드번호와 같은 이유).
룰 본문만 여기 있고, 숫자가 들어갈 자리는 {}로 비워 둔다.
"""
from check import load

# 포켓몬 것 그대로. 이름을 성경식으로 바꾸지 않는 이유: 이미 구운 카드 3장(036/077/078)에
# "독 상태로 만든다"가 인쇄돼 있다. 바꾸면 그 카드를 다시 뽑아야 한다.
CONDITIONS = [
    ("독", "턴이 끝날 때 데미지 카운터 1개(10). 벤치로 물러나면 풀린다."),
    ("화상", "턴이 끝날 때 동전을 던져 뒷면이면 데미지 카운터 2개(20). 벤치로 물러나면 풀린다."),
    ("마비", "공격도 후퇴도 못 한다. 다음 내 턴이 끝날 때 풀린다."),
    ("잠듦", "공격도 후퇴도 못 한다. 턴이 끝날 때 동전을 던져 앞면이면 풀린다."),
    ("혼란", "공격할 때 동전을 던져 뒷면이면 공격이 빗나가고 자기 자신에게 30."),
]

TRAINERS = [
    ("아이템", "턴에 몇 장이든 쓴다. 쓰고 나면 버린다."),
    ("서포터", "턴에 한 장만 쓴다. 쓰고 나면 버린다."),
    ("스타디움", "필드 가운데에 펼쳐 두고 양쪽 모두에게 효과를 준다. "
                 "턴에 한 장만 내고, 새 스타디움이 나오면 먼저 있던 것을 버린다."),
]

def md(d, weak, resist):
    R, ring, pack = d["rules"], d["ring"], d["rules"]["pack"]
    S, P = d["set"], R["prize_label"]
    n人 = sum(1 for c in d["cards"] if c["kind"] == "인물")
    return f"""# 성경 TCG 룰북 — {S["name"]} ({S["code"]})

카드 {len(d["cards"])}종 (인물 {n人} / 트레이너 {len(d["cards"]) - n人}) + 기본 에너지 {len(ring)}종.
`python3 rulebook.py`로 생성된다 — 수치를 고치려면 cards.json을 고칠 것.

## 승리 조건 (셋 중 하나)
1. 내 영혼 카드 {R["prize_count"]}장을 다 가져온다
2. 상대 필드의 인물을 전부 쓰러뜨린다
3. 상대가 자기 턴 시작에 덱에서 뽑을 카드가 없다

영혼 카드는 같은 {R["prize_count"]}장인데 이름만 진영에 따라 다르다 —
천국은 **{P["천국"]}**, 지옥은 **{P["지옥"]}**.
같은 행동이 양쪽에서 반대 의미가 된다.

## 덱
- 정확히 **{R["deck_size"]}장**
- 같은 이름 카드는 **{R["max_copies_per_name"]}장**까지 (기본 에너지는 무제한)
- 기본 인물이 최소 {R["min_basic_in_deck"]}장 — 없으면 시작을 못 한다
- 진영을 섞어도 된다 ({"금지" if R["one_faction_per_deck"] else "허용"}). 대신 "내 필드 인물이 전부 천국이면" 같은
  조건부 카드가 한 진영으로만 짠 덱에 값을 준다

## 셋업
1. 덱을 섞고 손에 7장
2. 기본 인물을 1장 배틀 자리에 뒷면으로 놓는다. 기본 인물이 손에 없으면 **멀리건** —
   손을 덱에 섞어 다시 7장, 상대는 카드 1장을 더 뽑는다
3. 기본 인물을 벤치(최대 {R["bench_size"]}장)에 더 놓아도 된다
4. 덱 위에서 {R["prize_count"]}장을 뒷면으로 깔아 영혼 카드로 둔다
5. 동전으로 선공을 정하고 모두 앞면으로 뒤집는다. **선공 첫 턴은 공격할 수 없다**

## 턴 구조
1. **드로우** — 1장 (강제, 못 뽑으면 패배)
2. **액션** — 순서·횟수 제한 없이 섞어서
   - 기본 인물을 벤치에 놓기
   - 진화 (놓은 턴에는 진화 불가)
   - 에너지 부착 — **턴당 1장**
   - 아이템 / 스타디움 / 서포터 (서포터는 턴당 1장)
   - 후퇴 — **턴당 1회**, 후퇴 비용만큼 에너지를 버린다
3. **공격** — 배틀 인물의 기술 1개 → 턴 종료

## 데미지
HP 바를 쓰지 않는다. **카드 위에 데미지 카운터를 올린다** (카운터 1개 = 10).
누적 데미지가 HP 이상이면 쓰러진다 → 상대가 영혼 카드 1장을 가져간다.

계산 순서: 기술 데미지 → 약점 **x{R["weakness_multiplier"]}** → 저항 **{R["resistance"]}** → 그 외 효과.

## 상성 링
`{" → ".join(ring)} → {ring[0]}` — 화살표 쪽에 강하다.
N×N 표를 두지 않는다. 다섯 줄로 끝나고 어떤 타입도 최강이 되지 않는다.

| 타입 | 약점 (x{R["weakness_multiplier"]}) | 저항 ({R["resistance"]}) |
|---|---|---|
""" + "\n".join(f'| {t} | {weak[t]} | {resist[t]} |' for t in ring) + f"""

타입은 양 진영이 공유한다 — 천국 불과 지옥 불이 둘 다 있어서 같은 진영끼리 붙어도 상성이 돈다.
에너지도 같은 {len(ring)}원소를 쓴다 (진영 전용 에너지는 없다).

## 특수 상태
배틀 인물에게만 붙는다. 한 인물에게 마비·잠듦·혼란은 동시에 하나만.

""" + "\n".join(f'- **{n}** — {t}' for n, t in CONDITIONS) + """

## 트레이너 카드

""" + "\n".join(f'- **{n}** — {t}' for n, t in TRAINERS) + f"""

## 팩
한 팩 {pack["size"]}장 / {pack["price"]}코인. 시작 코인 {R["start_coins"]}.
슬롯: """ + " · ".join(f'{k} {v}' for k, v in pack["slots"].items()) + f""".
{pack["note"]}
이미 가진 카드가 또 나오면 {pack["dupe_refund"]}코인으로 돌려받는다.

가진 카드 안에서만 덱을 짠다 — 고정 덱 제품이 아니다.

## 희귀도
""" + "\n".join(f'- {r} {n}종' for r, n in
                [(r, sum(1 for c in d["cards"] if c["rarity"] == r)) for r in "●◆★"]) + """
"""

if __name__ == "__main__":
    d, weak, resist = load()
    open("rules.md", "w").write(md(d, weak, resist))
    print(f'rules.md 생성 — 카드 {len(d["cards"])}종 기준')
